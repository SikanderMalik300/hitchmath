export interface PageEntry {
  slug: string; // '' for home
  path: string; // trailing-slash URL path
  title: string; // <= 60 chars
  meta: string; // <= 155 chars
  h1: string;
  category: Category;
  description: string; // one-line, used on /sitemap/ and tiles
  tileName?: string; // short name for tiles
  tileLine?: string; // muted line under a tile
  related?: string[]; // slugs
  lastUpdated: string; // ISO date; changes only when content changes (= dateModified)
  datePublished?: string; // original publish date (defaults to lastUpdated)
  verified?: boolean; // false = pending browser-agent verification: noindex, off sitemap/llms/IndexNow/hub/home
  sources?: SourceId[];
  photoId?: PhotoId;
  ownerNote?: string; // empty in v1
  inSitemap: boolean; // listed in sitemap.xml and /sitemap/
}

